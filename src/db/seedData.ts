// Helper to generate 30 days of realistic historical sensor readings
export const generateInitialSensorReadings = (): SensorReading[] => {
  const readings: SensorReading[] = [];
  const now = Date.now();
  const dayMs = 24 * 3600 * 1000;

  for (let i = 29; i >= 0; i--) {
    const timestamp = new Date(now - i * dayMs);
    const wave = Math.sin(i * 0.45) * 8;
    const baseMoisture = Math.round(64 + wave + (i % 5 === 0 ? 8 : -3));
    const moisture = Math.max(34, Math.min(88, baseMoisture));
    const temp = Math.round(27 + Math.sin(i * 0.3) * 4);
    const humidity = Math.round(68 + Math.cos(i * 0.5) * 9);
    const rain = i === 12 || i === 22 || i === 2 ? Math.round(14 + (i % 4) * 5) : 0;

    readings.push({
      userId: DEMO_USER_ID,
      sensorId: 'sensor-01',
      farmId: 'farm-01',
      fieldId: 'field-01',
      timestamp: timestamp.toISOString(),
      readingDate: timestamp.toISOString().split('T')[0],
      readingTime: timestamp.toTimeString().slice(0, 5),
      moisturePercent: moisture,
      soilMoisture: moisture,
      temperatureC: temp,
      temperature: temp,
      humidityPercent: humidity,
      humidity: humidity,
      rainfallMm: rain,
      rainfall: rain,
      irrigationActive: moisture < 50,
      irrigationStatus: moisture < 50 ? 'ON' : 'OFF',
      isSimulated: true,
      source: 'simulated',
    });
  }

  // Today's hourly readings
  const hours = [0, 3, 6, 9, 12, 15, 18, 21];
  const today = new Date();
  today.setHours(0, 0, 0, 0);

  hours.forEach((hour) => {
    const time = new Date(today.getTime() + hour * 3600 * 1000);
    if (time.getTime() <= now) {
      const tempVariation = hour >= 6 && hour <= 15 ? (hour === 12 ? 31 : 28) : 25;
      const moistVariation = hour >= 9 && hour <= 15 ? 65 : 68;

      readings.push({
        userId: DEMO_USER_ID,
        sensorId: 'sensor-01',
        farmId: 'farm-01',
        fieldId: 'field-01',
        timestamp: time.toISOString(),
        readingDate: time.toISOString().split('T')[0],
        readingTime: time.toTimeString().slice(0, 5),
        moisturePercent: moistVariation,
        soilMoisture: moistVariation,
        temperatureC: tempVariation,
        temperature: tempVariation,
        humidityPercent: hour === 6 ? 80 : 68,
        humidity: hour === 6 ? 80 : 68,
        rainfallMm: 0,
        rainfall: 0,
        irrigationActive: false,
        irrigationStatus: 'OFF',
        isSimulated: true,
        source: 'simulated',
      });
    }
  });

  return readings;
};
